// 1. Исходный массив пользователей (создаем для примера)
const users = [
    { name: "Иван", age: 25 },
    { name: "Анна", age: 16 },
    { name: "Олег", age: 18 },
    { name: "Мария", age: 14 },
    { name: "Алексей", age: 30 }
];

// 2. Создаем первый новый массив: фильтруем тех, кто старше или равен 18
const adults = users.filter((user) => {
    return user.age >= 18;
});

// 3. Создаем второй новый массив: забираем только имена отфильтрованных пользователей
const adultNames = adults.map((user) => {
    return user.name;
});

// 4. Выводим результаты в консоль для проверки
console.log("Пользователи 18+:", adults);
console.log("Только их имена:", adultNames);
